#!/usr/bin/env python3
"""Copy the always-needed reference files into each SKILL.md.

Claude Code loads SKILL.md itself, without a permission check, but reading a
reference file is a normal Read outside the user's project and needs approval
(denied outright in `claude -p`). So the references a skill always needs are
inlined; the files in references/ stay the single source of truth.

Usage:  python3 scripts/inline-references.py          # rewrite SKILL.md files
        python3 scripts/inline-references.py --check  # exit 1 if any copy is stale
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BP = "skills/blueprints/references/"

INLINE = {
    "skills/blueprints/SKILL.md": [BP + "project-detection.md", BP + "blueprint-yaml.md",
                                   BP + "page-builder.md", BP + "templates.md"],
    "skills/forms/SKILL.md": [BP + "project-detection.md", "skills/forms/references/forms.md",
                              BP + "blueprint-yaml.md"],
    "skills/users/SKILL.md": [BP + "project-detection.md", "skills/users/references/permissions.md"],
}

BEGIN = "<!-- BEGIN INLINED REFERENCES: generated by scripts/inline-references.py, edit references/ instead -->"
END = "<!-- END INLINED REFERENCES -->"


def demote(text: str) -> str:
    """Shift headings two levels down (# -> ###), leaving code fences alone."""
    out, fenced = [], False
    for line in text.rstrip("\n").splitlines():
        if line.lstrip().startswith("```"):
            fenced = not fenced
        elif not fenced and line.startswith("#"):
            line = "##" + line
        out.append(line)
    return "\n".join(out)


def block(refs: list[str]) -> str:
    parts = [BEGIN, "", "## Inlined references", ""]
    for ref in refs:
        body = demote((ROOT / ref).read_text())
        parts += [f"<!-- source: {ref} -->", body, ""]
    parts.append(END)
    return "\n".join(parts) + "\n"


def render(skill: str, refs: list[str]) -> tuple[str, str]:
    path = ROOT / skill
    current = path.read_text()
    if BEGIN in current:
        head = current[: current.index(BEGIN)]
        tail = current[current.index(END) + len(END):].lstrip("\n")
    else:
        head, tail = current.rstrip("\n") + "\n\n", ""
    return current, head + block(refs) + (("\n" + tail) if tail else "")


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for skill, refs in INLINE.items():
        current, new = render(skill, refs)
        if current != new:
            stale.append(skill)
            if not check:
                (ROOT / skill).write_text(new)
    if check and stale:
        print("stale inlined references in: " + ", ".join(stale), file=sys.stderr)
        print("run: python3 scripts/inline-references.py", file=sys.stderr)
        return 1
    print(("up to date" if check else "updated: " + (", ".join(stale) or "nothing")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
